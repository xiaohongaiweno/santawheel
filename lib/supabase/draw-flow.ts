/**
 * How participants receive their assignment.
 *
 * - `email` — every participant supplies an email; we send one private link each
 * - `link`  — no participant emails at all; the organizer copies one private
 *             link per person and shares it through WhatsApp, Messenger, etc.
 */
export type DeliveryMode = "email" | "link";

export interface PrivateLink {
  participantId: string;
  name: string;
  url: string;
}

export interface CreateExchangeInput {
  title: string;
  /** Required for email delivery, optional for private links. */
  organizerEmail?: string;
  participants: IncomingParticipant[];
  /** [refA, refB] pairs that must not draw each other (bidirectional). */
  exclusions?: Array<[string, string]>;
  budgetAmount?: number;
  deadline?: string; // YYYY-MM-DD
  /** Landing page origin — switches email copy and keeps page data separate. */
  kind?: ExchangeKind;
  deliveryMode?: DeliveryMode;
  /** Never show pairings in the organizer dashboard (email delivery only). */
  blindMode?: boolean;
  /** Creator IP, stored for abuse rate limiting. */
  createdByIp?: string;
  /**
   * Idempotency key generated by the browser per form session. A retried
   * submission (double click, flaky network, refresh) resolves to the same
   * exchange instead of drawing — and emailing — everyone twice.
   */
  requestId?: string;
}

export interface CreateExchangeResult {
  exchangeId: string;
  reused: boolean;
  generation: number;
  deliveryMode: DeliveryMode;
  blindMode: boolean;
  /** Present for private-link draws: one unguessable link per participant. */
  links: PrivateLink[];
}

/** Raised when the database has not had the migration for a feature applied. */
class SchemaTooOldError extends Error {
  constructor(
    feature: string,
    migration = "20261104050000_delivery_modes.sql"
  ) {
    super(
      `${feature} needs a database migration that has not been applied yet. ` +
        `Run supabase/migrations/${migration} and try again.`
    );
    this.name = "SchemaTooOldError";
  }
}

/** Full pipeline: validate -> persist -> draw -> persist pairs -> enqueue emails. */
export async function createAndDeliverExchange(
  input: CreateExchangeInput
): Promise<CreateExchangeResult> {
  const title = input.title?.trim();
  if (!title) throw new Error("Title is required");

  const deliveryMode: DeliveryMode = input.deliveryMode === "link" ? "link" : "email";
  const blindMode = Boolean(input.blindMode);
  // A blind link-mode draw is a contradiction: the organizer physically holds
  // every link, so we refuse instead of making a privacy promise we cannot keep.
  if (blindMode && deliveryMode !== "email") {
    throw new Error("Blind mode is only available with email delivery");
  }

  const rawOrganizerEmail = (input.organizerEmail ?? "").toLowerCase().trim();
  if (deliveryMode === "email" && !EMAIL_RE.test(rawOrganizerEmail)) {
    throw new Error("A valid organizerEmail is required");
  }
  if (rawOrganizerEmail && !EMAIL_RE.test(rawOrganizerEmail)) {
    throw new Error("A valid organizerEmail is required");
  }
  const organizerEmail = rawOrganizerEmail || null;

  const participants = normalizeParticipants(input.participants, {
    requireEmail: deliveryMode === "email",
  });
  const kind: ExchangeKind = input.kind ?? "secret_santa";
  const requestId = normalizeRequestId(input.requestId);

  // Duplicate submission? Return the exchange that was already created for
  // this request instead of drawing (and emailing) everyone a second time.
  if (requestId) {
    const existing = await findExchangeByRequestId(requestId);
    if (existing) {
      // A retried link-mode submission still needs the links, or the organizer
      // lands on an empty success page and has no way to hand them out.
      const { data: row } = await getSupabaseAdmin()
        .from("exchange")
        .select("*")
        .eq("id", existing)
        .maybeSingle();
      const generation = Number(row?.draw_generation ?? 0);
      const existingMode: DeliveryMode =
        row?.delivery_mode === "link" ? "link" : "email";
      return {
        exchangeId: existing,
        reused: true,
        generation,
        deliveryMode: existingMode,
        blindMode: Boolean(row?.blind_mode),
        links:
          existingMode === "link" && row?.status === "drawn" && generation > 0
            ? await privateLinksFor(existing, generation)
            : [],
      };
    }
  }

  const exchangeId = await insertExchange({
    title,
    organizerEmail,
    kind,
    budgetAmount: input.budgetAmount,
    deadline: input.deadline,
    createdByIp: input.createdByIp,
    requestId,
    deliveryMode,
    blindMode,
  });

  try {
    const { data: participantRows, error: perr } = await getSupabaseAdmin()
      .from("participant")
      .insert(
        participants.map((p) => ({
          exchange_id: exchangeId,
          name: p.name,
          email: p.email || null,
          note: p.note ?? null,
          wishlist_url: p.wishlistUrl ?? null,
        }))
      )
      .select("*");
    if (perr) {
      // email is NOT NULL until the delivery-mode migration lands.
      if (perr.code === "23502" && deliveryMode === "link") {
        throw new SchemaTooOldError("Private link mode");
      }
      throw new Error(`addParticipants failed: ${perr.message}`);
    }

    const rows = participantRows as ParticipantRow[];
    const exclusionPairs = await insertExclusions(exchangeId, rows, input.exclusions ?? []);

    const generation = await drawAndDeliver({
      exchangeId,
      participants: rows,
      exclusionIds: exclusionPairs,
      organizerEmail,
      title,
      kind,
      deliveryMode,
      blindMode,
    });

    return {
      exchangeId,
      reused: false,
      generation,
      deliveryMode,
      blindMode,
      links:
        deliveryMode === "link"
          ? rows.map((p) => ({
              participantId: p.id,
              name: p.name,
              url: assignmentUrl(exchangeId, p.id, generation),
            }))
          : [],
    };
  } catch (e) {
    // Roll back the half-built exchange so no orphan rows linger.
    await getSupabaseAdmin().from("exchange").delete().eq("id", exchangeId);
    throw e;
  }
}

/** Insert the exchange row, degrading safely on an un-migrated database. */
async function insertExchange(input: {
  title: string;
  organizerEmail: string | null;
  kind: ExchangeKind;
  budgetAmount?: number;
  deadline?: string;
  createdByIp?: string;
  requestId: string | null;
  deliveryMode: DeliveryMode;
  blindMode: boolean;
}): Promise<string> {
  const db = getSupabaseAdmin();
  const base = {
    title: input.title,
    organizer_email: input.organizerEmail ?? "",
    budget_amount: input.budgetAmount ?? null,
    deadline: input.deadline ?? null,
    kind: input.kind,
    created_by_ip: input.createdByIp ?? null,
  };
  const modes = { delivery_mode: input.deliveryMode, blind_mode: input.blindMode };

  // Deploy-order safety: an older database has neither client_request_id nor
  // the delivery-mode columns. Only the *default* mode may fall back — a user
  // who asked for private links or blind mode must never silently get an
  // emailing, fully-visible draw.
  const attempts: Array<Record<string, unknown>> = [];
  if (input.requestId) attempts.push({ ...base, ...modes, client_request_id: input.requestId });
  attempts.push({ ...base, ...modes });
  if (input.requestId && input.deliveryMode === "email" && !input.blindMode) {
    attempts.push({ ...base, client_request_id: input.requestId });
  }
  attempts.push({ ...base });

  let lastError: { code?: string; message: string } | null = null;
  for (let i = 0; i < attempts.length; i++) {
    const row = attempts[i];
    const { data, error } = await db.from("exchange").insert(row).select("id").single();
    if (!error) return data!.id as string;

    lastError = error;
    if (error.code === "23505" && input.requestId) {
      // Unique violation on client_request_id: a concurrent request won the race.
      const existing = await findExchangeByRequestId(input.requestId);
      if (existing) return existing;
    }
    if (error.code !== "42703" && error.code !== "PGRST204") break; // not a missing-column problem: give up

    // A missing column means this database is older than the code. If the next
    // attempt would drop the delivery-mode columns, the user would silently get
    // an emailing, fully-visible draw — refuse instead of downgrading.
    const next = attempts[i + 1];
    const wantsModes = input.deliveryMode === "link" || input.blindMode;
    if (wantsModes && "delivery_mode" in row && (!next || !("delivery_mode" in next))) {
      throw new SchemaTooOldError(input.blindMode ? "Blind mode" : "Private link mode");
    }
  }
  throw new Error(`createExchange failed: ${lastError?.message ?? "unknown error"}`);
}

/** Reset (revokes all links) then draw again with the current non-removed participants. */
export async function redrawExchange(exchangeId: string): Promise<{ generation: number }> {
  const db = getSupabaseAdmin();

  const { data: exchange } = await db
    .from("exchange")
    .select("*")
    .eq("id", exchangeId)
    .maybeSingle();
  if (!exchange) throw new Error("Exchange not found");

  const { error: resetErr } = await db.rpc("reset_draw", { p_exchange_id: exchangeId });
  if (resetErr) throw new Error(`reset_draw failed: ${resetErr.message}`);

  const { data: fresh } = await db
    .from("exchange")
    .select("draw_generation")
    .eq("id", exchangeId)
    .single();
  if (!fresh) throw new Error("Exchange disappeared during reset");
  const generation = fresh.draw_generation as number;

  const { data: participants, error: perr } = await db
    .from("participant")
    .select("*")
    .eq("exchange_id", exchangeId)
    .is("removed_at", null);
  if (perr) throw new Error(`fetchParticipants failed: ${perr.message}`);
  const rows = participants as ParticipantRow[];

  const { data: exclusionRows } = await db
    .from("exclusion")
    .select("participant_a, participant_b")
    .eq("exchange_id", exchangeId);
  const ids = new Set(rows.map((r) => r.id));
  const exclusionPairs: Array<[string, string]> = (exclusionRows ?? [])
    .filter((e) => ids.has(e.participant_a) && ids.has(e.participant_b))
    .map((e) => [`${e.participant_a}`, `${e.participant_b}`]);

  await drawAndDeliver({
    exchangeId,
    participants: rows,
    exclusionIds: exclusionPairs,
    organizerEmail: (exchange.organizer_email as string) || null,
    title: exchange.title as string,
    kind: (exchange.kind as ExchangeKind) ?? "secret_santa",
    deliveryMode: (exchange.delivery_mode as DeliveryMode) ?? "email",
    blindMode: Boolean(exchange.blind_mode),
  });
  return { generation };
}

async function drawAndDeliver(input: {
  exchangeId: string;
  participants: ParticipantRow[];
  exclusionIds: Array<[string, string]>;
  organizerEmail: string | null;
  title: string;
  kind: ExchangeKind;
  deliveryMode: DeliveryMode;
  blindMode: boolean;
}): Promise<number> {
  const db = getSupabaseAdmin();
  const {
    exchangeId,
    participants,
    exclusionIds,
    organizerEmail,
    title,
    kind,
    deliveryMode,
    blindMode,
  } = input;
  const label = kindLabel(kind);

  const { data: exchangeRow } = await db
    .from("exchange")
    .select("paid")
    .eq("id", exchangeId)
    .single();
  const paid = Boolean(exchangeRow?.paid);

  // Draw is computed over stable display keys, then mapped back to ids.
  const keyOf = (p: ParticipantRow) => participantKey(p);
  const idByKey = new Map(participants.map((p) => [keyOf(p), p.id] as const));
  const names = participants.map(keyOf);
  const exclusions = exclusionIds.map(([a, b]) => {
    const pa = participants.find((p) => p.id === a);
    const pb = participants.find((p) => p.id === b);
    return [keyOf(pa!), keyOf(pb!)] as [string, string];
  });

  // Premium: no-repeat draws — previous pairings from this organizer become
  // extra exclusion constraints.
  if (paid && organizerEmail) {
    const { data: history } = await db
      .from("pair_history")
      .select("giver_email, receiver_email")
      .eq("organizer_email", organizerEmail);
    const emailToKey = new Map(
      participants.filter((p) => p.email).map((p) => [p.email, keyOf(p)] as const)
    );
    for (const h of (history ?? []) as Array<{ giver_email: string; receiver_email: string }>) {
      const g = emailToKey.get(h.giver_email);
      const r = emailToKey.get(h.receiver_email);
      if (g && r) exclusions.push([g, r]);
    }
  }

  const draw = buildDraw(names, exclusions); // throws UnsolvableDrawError when impossible
  const check = validateDraw(names, exclusions, draw);
  if (!check.ok) throw new Error(`internal error: invalid draw rejected (${check.reason})`);

  const pairs = draw.map((d) => ({
    giver: idByKey.get(d.giver)!,
    receiver: idByKey.get(d.receiver)!,
  }));

  const { error: rpcErr } = await db.rpc("perform_draw", {
    p_exchange_id: exchangeId,
    p_pairs: pairs,
  });
  if (rpcErr) throw new Error(`perform_draw failed: ${rpcErr.message}`);

  const { data: ex, error: exErr } = await db
    .from("exchange")
    .select("draw_generation")
    .eq("id", exchangeId)
    .single();
  if (exErr) throw new Error(`fetchGeneration failed: ${exErr.message}`);
  const generation = ex.draw_generation as number;

  // Delivery state only exists when we actually deliver by email.
  if (deliveryMode === "email") {
    const { error: aErr } = await db.from("assignment").insert(
      pairs.map((p) => ({
        exchange_id: exchangeId,
        giver_id: p.giver,
        draw_generation: generation,
      }))
    );
    if (aErr) throw new Error(`insertAssignments failed: ${aErr.message}`);
  }

  // Record history so future paid draws can avoid repeating pairs. History is
  // keyed by email, so link-mode draws (no emails) simply skip it.
  if (organizerEmail) {
    const byId = new Map(participants.map((p) => [p.id, p] as const));
    const historyRows = pairs
      .map((p) => ({
        organizer_email: organizerEmail,
        giver_email: byId.get(p.giver)!.email ?? "",
        receiver_email: byId.get(p.receiver)!.email ?? "",
        exchange_id: exchangeId,
      }))
      .filter((r) => r.giver_email && r.receiver_email);
    if (historyRows.length > 0) {
      const { error: hErr } = await db
        .from("pair_history")
        .upsert(historyRows, { onConflict: "exchange_id,giver_email,receiver_email" });
      if (hErr) throw new Error(`recordPairHistory failed: ${hErr.message}`);
    }
  }

  // Reset reminder scheduling for the new draw.
  const reminderAt =
    paid && deliveryMode === "email"
      ? new Date(Date.now() + 3 * 24 * 60 * 60 * 1000).toISOString()
      : null;
  const { error: rErr } = await db
    .from("exchange")
    .update({ reminder_sent: false, reminder_at: reminderAt })
    .eq("id", exchangeId);
  if (rErr) throw new Error(`resetReminder failed: ${rErr.message}`);

  const jobs: EnqueueInput[] = [];
  if (deliveryMode === "email") {
    for (const p of participants) {
      if (!p.email) continue;
      jobs.push({
        exchangeId,
        kind: "assignment",
        giverId: p.id,
        toEmail: p.email,
        subject: `Your ${label} assignment`,
        payload: {
          name: p.name,
          kind,
          token: signToken({ t: "a", x: exchangeId, p: p.id, g: generation }),
          removeToken: signToken({ t: "r", x: exchangeId, p: p.id }),
          assignmentUrl: assignmentLink(exchangeId, p.id, generation),
        },
      });
    }
  }
  if (organizerEmail) {
    jobs.push({
      exchangeId,
      kind: "organizer_link",
      giverId: null,
      toEmail: organizerEmail,
      subject: blindMode
        ? "Your SantaWheel draw is ready — blind mode"
        : "Your SantaWheel draw is ready",
      payload: {
        title,
        kind,
        blind: blindMode,
        deliveryMode,
        token: signToken({ t: "o", x: exchangeId }),
        manageUrl: manageLink(exchangeId),
      },
    });
  }

  await enqueueEmails(jobs);
  return generation;
}

/**
 * Resolve organizer-typed exclusion refs (an email, or a unique name in link
 * mode) to participant ids and store them in normalised order.
 */
async function insertExclusions(
  exchangeId: string,
  participants: ParticipantRow[],
  refs: Array<[string, string]>
): Promise<Array<[string, string]>> {
  if (refs.length === 0) return [];

  const byEmail = new Map(
    participants.filter((p) => p.email).map((p) => [p.email.toLowerCase(), p.id] as const)
  );
  const nameCount = new Map<string, number>();
  for (const p of participants) {
    const key = p.name.trim().toLowerCase();
    nameCount.set(key, (nameCount.get(key) ?? 0) + 1);
  }
  const byName = new Map(
    participants
      .filter((p) => nameCount.get(p.name.trim().toLowerCase()) === 1)
      .map((p) => [p.name.trim().toLowerCase(), p.id] as const)
  );

  const resolve = (raw: string): string | null => {
    const s = raw.trim().toLowerCase();
    return byEmail.get(s) ?? byName.get(s) ?? null;
  };

  const rows: Array<{ exchange_id: string; participant_a: string; participant_b: string }> = [];
  const validPairs: Array<[string, string]> = [];
  for (const [a, b] of refs) {
    const idA = resolve(a);
    const idB = resolve(b);
    const missing = [idA ? null : a, idB ? null : b].filter(Boolean) as string[];
    if (!idA || !idB) {
      throw new Error(`Exclusion references unknown participant(s): ${missing.join(", ")}`);
    }
    if (idA === idB) continue;
    const [lo, hi] = idA < idB ? [idA, idB] : [idB, idA];
    rows.push({ exchange_id: exchangeId, participant_a: lo, participant_b: hi });
    validPairs.push([idA, idB]);
  }
  if (rows.length > 0) {
    const { error } = await getSupabaseAdmin()
      .from("exclusion")
      .upsert(rows, { onConflict: "exchange_id,participant_a,participant_b" });
    if (error) throw new Error(`insertExclusions failed: ${error.message}`);
  }
  return validPairs;
}

/** One private result link per active participant (link mode only). */
async function privateLinksFor(exchangeId: string, generation: number): Promise<PrivateLink[]> {
  const { data } = await getSupabaseAdmin()
    .from("participant")
    .select("id, name")
    .eq("exchange_id", exchangeId)
    .is("removed_at", null);
  return ((data ?? []) as Array<{ id: string; name: string }>).map((p) => ({
    participantId: p.id,
    name: p.name,
    url: assignmentUrl(exchangeId, p.id, generation),
  }));
}

/** Look up an exchange created for this idempotency key (null when unknown). */async function findExchangeByRequestId(requestId: string): Promise<string | null> {
  const { data, error } = await getSupabaseAdmin()
    .from("exchange")
    .select("id")
    .eq("client_request_id", requestId)
    .maybeSingle();
  // Unknown column (migration not applied yet) must not break creation — the
  // insert will fail with a clear error instead, but lookup stays best-effort.
  if (error || !data) return null;
  return data.id as string;
}

/** GDPR: redact a participant immediately; hard deletion happens on next reset. */
export async function redactParticipant(exchangeId: string, participantId: string): Promise<void> {
  const db = getSupabaseAdmin();
  const now = new Date().toISOString();

  const { error } = await db
    .from("participant")
    .update({
      name: "Removed participant",
      email: `removed.${participantId}@invalid`,
      note: null,
      wishlist_url: null,
      removed_at: now,
    })
    .eq("exchange_id", exchangeId)
    .eq("id", participantId);
  if (error) throw new Error(`redactParticipant failed: ${error.message}`);

  // Stop any scheduled mail for them; their delivered assignment becomes void.
  await db
    .from("assignment")
    .update({ email_status: "cancelled", last_error: "participant removed their data" })
    .eq("exchange_id", exchangeId)
    .eq("giver_id", participantId);
  await db
    .from("email_job")
    .delete()
    .eq("exchange_id", exchangeId)
    .eq("giver_id", participantId)
    .eq("status", "pending");
}

/** Premium: bulk-add participants to an existing exchange (dedup by email). */
export async function importParticipants(
  exchangeId: string,
  incoming: Array<{ name: string; email?: string; wishlistUrl?: string }>
): Promise<{ added: number; skipped: number; invalid: string[] }> {
  const db = getSupabaseAdmin();
  const { data: existing } = await db
    .from("participant")
    .select("email")
    .eq("exchange_id", exchangeId);
  const known = new Set(((existing ?? []) as Array<{ email: string | null }>).map((e) => e.email));

  const invalid: string[] = [];
  const rows: Array<{ exchange_id: string; name: string; email: string; wishlist_url: string | null }> = [];
  for (const p of incoming) {
    const name = p.name?.trim();
    const email = (p.email ?? "").toLowerCase().trim();
    if (!name || !EMAIL_RE.test(email)) {
      invalid.push(`${name || email || "row"} — need a name and a valid email`);
      continue;
    }
    if (known.has(email)) continue; // already in the exchange
    known.add(email); // dedup within the batch
    rows.push({
      exchange_id: exchangeId,
      name,
      email,
      wishlist_url: p.wishlistUrl ?? null,
    });
  }

  if (rows.length > 0) {
    const { error } = await db.from("participant").insert(rows);
    if (error) throw new Error(`importParticipants failed: ${error.message}`);
  }
  return { added: rows.length, skipped: incoming.length - rows.length - invalid.length, invalid };
}

/**
 * GDPR: destroy an entire exchange and everything attached to it.
 *
 * The privacy policy tells organizers they can ask us to delete the whole
 * draw. Pairs are protected by immutability triggers, so this must go through
 * purge_exchange(), which opens the same transaction-scoped bypass that
 * reset_draw() uses. Irreversible — the API requires an explicit confirmation.
 */
export async function purgeExchange(exchangeId: string): Promise<void> {
  const db = getSupabaseAdmin();
  const { error } = await db.rpc("purge_exchange", { p_exchange_id: exchangeId });
  if (!error) return;

  // Function missing => migration not applied. Fail loudly instead of
  // pretending the data is gone.
  if (
    error.code === "PGRST202" ||
    /could not find the function|does not exist/i.test(error.message)
  ) {
    throw new SchemaTooOldError("Deleting a draw", "20261104060000_purge_exchange.sql");
  }
  throw new Error(`purge_exchange failed: ${error.message}`);
}
